/* Команды модулей и точка входа модуля (выпуск 1.10, шаг 4; docs/architecture.md, «Процессы»).
 *
 * Один файл (modcmd.c), два потребителя: steerd (заглушки — команда есть у модуля, запускаем его
 * или отказываем словами «нужен пакет») и бинарник каждого модуля (steer-vless и остальные:
 * настоящие команды). Слабые ссылки на cmd_* решают, чьё дело — команда: в бинарнике модуля они
 * определены, в steerd без модуля — нет, а в статических сборках (телефон, стенды) определены
 * в самом steerd, и заглушка не понадобится вовсе. */
#ifndef STEER_MODCMD_H
#define STEER_MODCMD_H

struct cli_args;
struct spec;

#define MODCMD_NONE (-1000)     /* команда не модульная — её разбирает вызывающий */

/* Выполнить модульную команду cmd. argc/argv — командная строка целиком (после --platform), на
 * случай, когда команду надо передать модулю: тот же разбор в нём даёт те же значения.
 * cfg — область под спеку (большая, статическая у вызывающего). MODCMD_NONE — не наша. */
int modcmd_run(const char *cmd, int argc, char **argv, const struct cli_args *a,
               const char *spec, const char *arg, struct spec *cfg);

/* 1 — команда выполняется в этом бинарнике (модуль слинкован в него, как в статических сборках);
 * 0 — её ведёт отдельный модуль или её нет. Демон по этому решает, запускать ли помощника
 * бинарником модуля (daemon/helpers.c). */
int modcmd_builtin(const char *cmd);

/* Вынуть из argv пару «--platform ИМЯ» и выбрать платформу. 0 — выбрана или не названа; 2 —
 * отказ (уже напечатан). Общая для steerd и модулей: платформа — до всего остального. */
int modcmd_platform_args(int *argc, char **argv);

/* main() бинарника модуля: платформа, hello в линию событий, справка, разбор аргументов и команда.
 * module — короткое имя («vless»), version — версия ЭТОГО бинарника (STEER_VERSION его единицы
 * компиляции): демон сверяет её со своей (hello, docs/ctl.md). */
int steer_module_main(int argc, char **argv, const char *module, const char *version);

#endif
