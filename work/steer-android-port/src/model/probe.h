#ifndef STEER_PROBE_H
#define STEER_PROBE_H
#include <stddef.h>

/* ---- подъём выхода vless: состояние, у которого раньше не было имени --------------------
 *
 * Устройство туннеля vless появляется НЕ СРАЗУ. При `node: -1` («первый рабочий» — умолчание
 * и то, что рекомендует интерфейс) клиент перебирает узлы подписки с таймаутом восемь секунд
 * на узел, и устройство создаётся только после выбора. Пока перебор идёт, устройства нет — и
 * диагностика печатала «устройства нет, туннель не поднят», то есть в точности то же, что при
 * настоящем отказе. На подписке из трёх десятков нерабочих узлов это минуты видимого «не
 * работает» на исправной настройке, и наоборот: настоящий отказ выглядел медленной проверкой
 * (I-100).
 *
 * Поэтому клиент рассказывает о ходе перебора файлом в state_dir, а status и diag его читают.
 * Файл, а не ubus: движок ubus-сервисом не является, а управляющий слой уже читает его вывод.
 *
 * УСТАРЕВАНИЕ обезврежено по-разному для двух состояний, и это главное в этой паре функций.
 * `probing` верен, только пока жив написавший его процесс, — проверяется по /proc/<pid>;
 * `failed` обязан пережить смерть процесса (клиент выходит с кодом 1, procd поднимает его
 * заново каждые пять секунд), поэтому верен, пока свеж. Отсутствие файла и устаревший файл
 * читаются как «не знаем» и возвращают PROBE_NONE — то есть прежнее поведение, а не жёлтая
 * метка на исправном роутере. */
enum probe_state {
    PROBE_NONE = 0,   /* нечего сказать: файла нет, он устарел или писавший процесс мёртв */
    PROBE_RUNNING,    /* перебор идёт: проверяется узел `node` из `total` */
    PROBE_FAILED,     /* перебор кончился: ни один узел не ответил (total>0) либо узлов нет */
    /* Выбранный НОМЕР узла за пределами подписки: узлы в ней есть, а такого номера нет.
     *
     * Отдельное состояние, а не разновидность PROBE_FAILED, и это не педантизм — это
     * исправление вранья, снятого с живого роутера. Раньше сюда писался `failed` с total=0,
     * то есть ровно та же запись, что у «в подписке нет пригодных узлов». Диагностика по ней
     * и говорила: «подписка скачана, но узлов нужного вида в ней нет» — на подписке из
     * ДВАДЦАТИ ДЕВЯТИ живых узлов, где человек всего лишь написал `node: 31`. Такой ответ
     * отправляет перекачивать подписку и менять провайдера вместо того, чтобы поправить одно
     * число; сам движок при этом знает правду и печатает её в `vless-probe`.
     *
     * `node` здесь — номер, который написал ЧЕЛОВЕК (первый из выбранных), `total` — сколько
     * пригодных узлов в подписке на самом деле. Двух этих чисел рядом достаточно, чтобы
     * причина читалась без journal. */
    PROBE_NO_SUCH_NODE,
    /* Узел был выбран, устройство есть, а потом узел перестал отвечать — клиент заметил это
     * сам (слежка за узлом, src/tunnel/pool.c) и сказал down. Только под демоном: слежку
     * клиент ведёт, лишь когда его слушает демон, и в файл probe-* это состояние не пишется
     * никогда — его знают только память демона и окружение его детей. Отдельное состояние,
     * а не PROBE_FAILED: устройство на месте, и «ни один узел подписки не ответил» было бы
     * неправдой о подъёме, которого не было. why — причина от клиента, since — с какого
     * времени (секунды Unix). */
    PROBE_LOST,
    /* Все кандидаты выхода исключены его `exclude`/`exclude_name` (выбранный узел отмечен исключённым
     * или исключение накрыло всю подписку). Отдельное состояние, а не PROBE_FAILED с total=0: та
     * запись говорит «в подписке нет пригодных узлов», а узлы есть — человек сам не велел их брать,
     * и чинится это в «Не брать», а не в подписке. total — сколько кандидатов было до исключения. */
    PROBE_ALL_EXCLUDED,
};

struct probe_status {
    enum probe_state state;
    /* Номер узла: у PROBE_RUNNING — проверяемый (с единицы), у PROBE_NO_SUCH_NODE — тот,
     * что выбрал человек (как написан в спеке), у PROBE_FAILED и PROBE_LOST — 0. */
    int node;
    int total;        /* сколько пригодных узлов нашлось в подписке */
    /* Только у PROBE_LOST, иначе пусто и 0. Буфер — по мерке причины клиента (до 159 байт,
     * pl_down_event в src/tunnel/pool.c), длиннее — обрезка по границе знака. */
    long since;
    char why[160];
};

/* Записать ход перебора. node с единицы; total — сколько пригодных узлов. */
void probe_report(const char *out_name, enum probe_state st, int node, int total);
/* Убрать запись: устройство поднялось, объяснять больше нечего. */
void probe_clear(const char *out_name);
/* Прочитать. PROBE_NONE, если сказать нечего. */
struct probe_status probe_read(const char *out_name);

/* ПАМЯТЬ ДЕМОНА ВМЕСТО ФАЙЛА. Демон с --supervise держит клиентов vless детьми и знает ход
 * перебора по их событиям (src/daemon/supd.c); клиент с трубой событий файла не пишет — флеш
 * телефона незачем изнашивать записью раз в восемь секунд. Тогда probe_read отвечает из памяти:
 *   - в самом демоне (status отвечает в процессе) — через probe_source: fn возвращает 0 и
 *     заполняет *st, если выход ей известен, иначе -1, и тогда читается файл, как прежде;
 *   - в детях демона (diag и прочие подкоманды) — из переменной окружения STEER_PROBE_MEM,
 *     которую демон ставит им при запуске: «выход:состояние:узел:всего» через пробел, состояние
 *     — probing, failed, nonode, excluded, lost или none; у lost ещё «:с какого времени:причина», и в
 *     причине пробел, «%» и «:» записаны как %20, %25 и %3A (probe_mem_escape). Выхода там
 *     нет — читается файл.
 * Ответ из памяти — то же перечисление и те же числа, что дала бы запись клиента; PROBE_LOST
 * бывает только отсюда. */
void probe_source(int (*fn)(const char *out_name, struct probe_status *st));

/* Причину PROBE_LOST — в запись STEER_PROBE_MEM (dst, n байт, с конечным нулём). Кодируются
 * только пробел, «%», «:» и управляющие байты: остальное, включая кириллицу, идёт как есть. */
void probe_mem_escape(const char *why, char *dst, size_t n);

#endif
