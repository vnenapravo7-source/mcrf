/* Адрес проверки задержки группы (`url` у `pick: latency`, docs/spec-v2.md) — разбор и вопрос
 * «есть ли в сборке HTTPS».
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ЗАМЕРА (src/daemon/urltest.c). Разбор нужен двоим: модели — чтобы негодный
 * адрес был отказом разбора спеки с местом в тексте, а не молчаливым «задержку измерить не
 * удалось» у сторожа, — и самому замеру. Модель компонуется стендами без демона и цикла событий,
 * поэтому разбор — чистая функция на одной libc, в слое видов (там же, где настройка группы). */
#ifndef STEER_GRPURL_H
#define STEER_GRPURL_H

#include <stddef.h>

/* Умолчание — HTTP, а не HTTPS, по двум причинам. Первая: steer-mini собирается без TLS, и одно
 * умолчание на оба пакета значит, что спека без `url` значит одно и то же в обоих. Вторая: время
 * до первого байта через туннель — это путь «туннель → сервер туннеля → проверочный узел», и
 * рукопожатие TLS сверху прибавляет к нему лишь два оборота того же пути. cp.cloudflare.com —
 * узел проверки плена Cloudflare: отвечает 204 без тела, anycast (задержка — до ближайшей к выходу
 * туннеля точки, а не до одного континента), ответ крошечный. */
#define GROUP_URL_DEFAULT "http://cp.cloudflare.com/generate_204"
/* Предел длины записи `url` в спеке (с завершающим нулём). */
#define GROUP_URL_MAX 192

struct urltest_url {
    int https;
    char host[128];
    unsigned short port;
    char path[160];
};

/* Разобрать http[s]://хост[:порт][/путь]. Хост — имя или литерал IPv4. 0 — годен, u заполнен
 * (путь по умолчанию "/", порт — 80 или 443 по схеме); -1 — негоден, почему — в why. */
int urltest_url_parse(const char *url, struct urltest_url *u, char *why, size_t wn);

/* Есть ли в этой сборке HTTPS для замера: полный пакет несёт src/proto/tls/urltls.c, мини — нет.
 * Вопрос к слабой ссылке, а не #ifdef: модель одна на все профили (build/sources.mk). */
int urltest_https_ok(void);

/* Отказать ли при разборе адресу https://: да там, где замер ведётся и HTTPS в сборке нет
 * (steer-mini), нет — в процессе, объявившем себя читателем (urltest_reader_only). */
int urltest_https_refused(void);

/* Вызывается в начале модуля (до load_spec): этот процесс спеку читает и группы не меряет, так что
 * доступность HTTPS для замера — не его вопрос. Доводы — в grpurl.c. */
void urltest_reader_only(void);

#endif
