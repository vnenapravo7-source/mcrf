#ifndef STEER_NFTCOMPAT_H
#define STEER_NFTCOMPAT_H
#include <stddef.h>
#include <stdio.h>

/* ---- nftables старого ядра: раскладка правил для Linux 4.9 ---------------------------
 *
 * ЗАЧЕМ. Набор правил движка написан под nftables современного ядра, и на 4.9 (телефон
 * Xiaomi beryllium, ядро LineageOS 4.9.337) он не загружается даже с включённым nf_tables:
 * `nft -f` атомарен, и одна непонятная ядру строка снимает всю транзакцию — не встают ни
 * наборы, ни метки, ни заворот DNS. Сверено по исходникам ядра 4.9, а не по документации;
 * вот чего там нет из того, что нам нужно:
 *
 *   - цепочек `type nat` в семействе inet: nf_tables_inet.c регистрирует только filter, nat
 *     есть лишь у ip и ip6 (nft_chain_nat_ipv4/ipv6). Появились в inet с 5.2. Вместе с ними
 *     в inet недоступны redirect и dnat;
 *   - наборов `flags interval,timeout`: у nft_set_rbtree (единственный интервальный) в 4.9
 *     features = INTERVAL|MAP, сроки жизни умеет только nft_set_hash (MAP|TIMEOUT);
 *   - `notrack`: в nft_ct.c upstream 4.9 и в ядре телефона его нет (с 4.10); Debian перенёс
 *     его в своё 4.9, поэтому он спрашивается у ядра отдельно (NFTC_NOTRACK);
 *   - `exthdr … exists`: флага NFT_EXTHDR_F_PRESENT нет (с 4.10), и это хуже отказа — ядро
 *     молча отбрасывает незнакомый атрибут и грузит ДРУГОЕ правило: `exthdr frag exists`
 *     становится сравнением поля `frag nexthdr` с единицей (снято на стенде tools/vm49);
 *   - получения одного элемента (`nft get element`): NFT_MSG_GETSETELEM отвечает только на
 *     дамп, иначе -EOPNOTSUPP (с 4.15) — это ломает не загрузку, а explain;
 *   - нескольких базовых цепочек nat на одном хуке: до 4.18 первая же цепочка nat, где
 *     ничего не совпало, ставит соединению «пустую» трансляцию, и остальные цепочки того же
 *     хука его больше не видят. Три наших цепочки на prerouting (DNS, fakeip, мост Telegram)
 *     на 4.9 означали бы, что работает только первая.
 *
 * Имена наборов и цепочек там ограничены 31 символом (NFT_*_MAXNAMELEN 32) — имена групп
 * рассчитаны на это давно (см. group_set_name), а суффикс статической части набора ниже
 * укладывается в тот же предел.
 *
 * Возвращает набор флагов NFTC_*; ноль — современное ядро, прежний набор правил байт в байт.
 * Выбор — пробой ядра (`nft -c` пробной таблицы inet с цепочкой nat), с переопределением
 * переменной STEER_NFT_COMPAT: modern, legacy (необязательное — нат в ip6 и notrack — всё
 * равно спрашивается у ядра) или legacy-min (без них и без проб: ровно то, что умеет ядро
 * телефона в конфиге LineageOS, и один и тот же текст для стендов). Ответ запоминается на
 * процесс. Определена в nftcompat.c. */
#define NFTC_LEGACY 1   /* раскладка для 4.9: nat в ip/ip6, наборы со сроками отдельно */
#define NFTC_IP6NAT 2   /* при NFTC_LEGACY: ядро принимает nat в ip6 (заворот DNS по IPv6) */
#define NFTC_NOTRACK 4  /* при NFTC_LEGACY: ядро знает выражение notrack (Debian перенёс его в 4.9) */
/* Без NFTC_LEGACY: ядро и nft принимают базовую цепочку на хуке ingress в семействе inet (Linux
 * 5.10, nftables 0.9.7), и разметку каналов ставит цепочка ingress_mark (generate.c, «разметка
 * на ingress»). nft_compat этот бит НЕ ставит: его добавляет apply_prepare по nft_ingress_ok, а
 * дальше он ходит вместе с раскладкой — план apply-сверки печатает g_nftc, демон отдаёт его
 * следующим планам через --nftc, — и проба не повторяется на каждый apply. Резолверу (dnsd) и
 * читателям ядра (nft_compat_seen) бит не нужен, и лишнего `nft -c` у них нет. */
#define NFTC_INGRESS 8
int nft_compat(void);
/* Примет ли ядро цепочку inet ingress: проба `nft -c` пробной таблицей с такой цепочкой на lo
 * (1 — да). STEER_NFT_INGRESS переопределяет ответ для стендов: 0 — нет; 1 — да (устройства
 * раздачи всё равно проверяются: цепочка встаёт только на существующие); all — да, и все
 * устройства раздачи считаются существующими (стенды генератора на машине без br-lan).
 * STEER_NFT_COMPAT=modern без него — «да» без пробы, старая раскладка — «нет». Ответ
 * запоминается на процесс. */
int nft_ingress_ok(void);
/* STEER_NFT_INGRESS=all: устройства раздачи не проверяются на существование. */
int nft_ingress_all_devs(void);
/* Раскладка, которая СТОИТ в ядре, — для тех, кто ядро только читает (diag, explain): старая —
 * если есть таблица ip движка (nat старой раскладки живёт там). Без проб `nft -c`: они решают,
 * что применять, а читателю нужно то, что применено. STEER_NFT_COMPAT — как у nft_compat. */
int nft_compat_seen(void);
/* nft_compat_seen с битом NFTC_IP6NAT (по цепочке nat в таблице ip6) — для таблицы каналов
 * резолвера, без процессов (см. определение). */
int nft_compat_seen6(void);
/* Примет ли ядро составной интервальный набор ipv4_addr . inet_proto . inet_service — для
 * каналов со смешанным сужением списка (см. nftcompat.c). 1 — да, 0 — делить по группам. */
int nft_concat_ok(void);

/* Имя статической (интервальной) половины доменного набора в раскладке legacy: «<имя>_n».
 * Динамическая половина, куда резолвер кладёт адреса со сроком, сохраняет имя группы — тогда
 * резолверу, explain и diag не нужно второе правило именования, а переименование не трогает
 * перенос счётчиков (он идёт по комментарию правила, то есть по имени группы). */
static inline void nft_static_set_name(char *dst, size_t n, const char *group) {
    snprintf(dst, n, "%.63s_n", group);
}

#endif
