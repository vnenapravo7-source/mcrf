#ifndef STEER_DNSD_FPSEED_H
#define STEER_DNSD_FPSEED_H

/* ЗАСЕВ НАБОРОВ КАНАЛОВ fake-IP — для печатника набора правил (src/compile/print.c).
 *
 * Карта подмены (fakeip, fakeip6) засевается в тексте набора правил из файла состояния резолвера
 * давно (emit_fakeip_elements в print.c). Наборы каналов — нет, и в промежутке между заменой
 * таблицы и приходом таблицы к резолверу пакет клиента к поддельному адресу из его кэша
 * разворачивался картой в настоящий адрес, а метки не получал: набор, по которому ставится метка,
 * был пуст. Пакет уходил по таблице main — в WAN, мимо выхода и мимо on_fail=drop. Подробно — в
 * шапке fpseed.c; порядок применения — docs/architecture.md, раздел 2, «Набор правил».
 *
 * Здесь — то, что резолвер сделал бы после таблицы (fakeip_rehydrate, fakeip.c), тем же кодом:
 * таблица каналов из спеки (dch_build), правила каналов из их списков (dch_rules_load), записи
 * файла состояния (fakeip_state_load), каналы имени (dch_match_mask, dch_fakeip_only,
 * dch_all_v6). Результат — элементы по наборам, которые печатник вписывает в тот же текст, что и
 * карту, то есть в ту же транзакцию nft -f.
 *
 * Слой: резолвер (src/dnsd) — ему одному известны правила каналов; компилятор о резолвере не
 * знает и спрашивает засев через указатель g_print_seed (ir.h), а ставит его точка входа apply
 * (src/daemon/apply.c) — слой выше обоих. */

#include <stddef.h>

struct spec;
struct ir_seed;

/* Собрать засев по спеке sp и файлу состояния path. 0 — собран (в том числе пустой: файла нет или
 * ни одно имя не входит ни в один канал fake-IP); -1 — не собран (память) — тогда засевать нельзя
 * и карту: подмена без решения о маршруте — ровно та утечка, от которой засев (см. apply.c). */
int fpseed_build(const struct spec *sp, const char *path);

/* Элементы засева набора set семейства fam (4 — имя набора канала, 6 — его парный «<набор>6»):
 * число и массив в *out, отсортированный по адресу, без повторов. Живёт до fpseed_free. Сигнатура —
 * та, что ждёт печатник (g_print_seed, ir.h). */
size_t fpseed_els(const char *set, int fam, const struct ir_seed **out);

/* Освободить всё, что собрал fpseed_build: таблицу каналов с правилами, записи файла состояния и
 * сам засев. */
void fpseed_free(void);

#endif
