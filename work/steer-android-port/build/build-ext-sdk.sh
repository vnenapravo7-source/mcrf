#!/bin/sh
# Расширенная половина движка, собранная ТУЛЧЕЙНОМ OpenWrt SDK, а не zig.
#
# ЗАЧЕМ ВТОРОЙ СПОСОБ СБОРКИ. Замер на живом роутере (mt7621, mipsel_24kc, tests/xsbench.c,
# нагрузка 1439 байт, одна и та же mbedtls 3.6.2, оба прогона по два раза):
#
#     zig 0.13.0, -O2            полный путь пакета 83 878 нс   AEAD 81 118 нс
#     SDK gcc 14.3.0, -O2        полный путь пакета 66 766 нс   AEAD 63 763 нс   (−20%)
#     SDK gcc 14.3.0, -Os        полный путь пакета 176 061 нс  AEAD 166 673 нс
#
# То есть GCC выпускает для ChaCha20-Poly1305 на MIPS32 код на пятую часть быстрее, чем LLVM, и
# ни -O3, ни -funroll-loops у zig этого не закрывают (проверено: 83 900 и 84 110 нс). На живом
# туннеле того же роутера, три прогона вперемежку: хаб → клиент 58,4 / 58,6 / 56,2 Мбит/с у SDK
# против 52,0 / 54,0 / 53,5 у zig — то есть около +8% устойчиво; на отдаче разброс стенда
# (36,3..48,7 у zig) перекрывает разницу, и про неё сказать нечего.
#
# Последняя строка таблицы — про умолчание OpenWrt: -Os стоит здесь ВДВОЕ дороже -O2 на шифре и в
# ТРИНАДЦАТЬ раз на контрольной сумме (36 890 нс против 2 826). Пакет, собранный обычным путём
# OpenWrt, был бы вдвое медленнее того, что мы выкладываем.
#
# ПО ВЕСУ РАЗМЕНА ТОЖЕ НЕТ, и это стоит сказать отдельно: расширенная половина выходит 574 552 байта
# против 687 980 у zig (−16,5%), хаб — 461 264 против 546 236 (−15,6%), пакет .apk — 288 050 против
# 314 863 (−8,5%). Сто тринадцать килобайт на overlay в 6,9 МБ не косметика.
#
# Здесь же ответ, почему LTO указан явно: zig включает его САМ (с -flto и без него размер один и тот
# же, 687 980), а gcc — нет, и без ключа сборка выходит на 15 КБ толще.
#
# ЧЕМ ПЛАТИМ ЗА SDK. Один zig на 45 МБ покрывает все ISA; SDK — это по 230 МБ на каждую цель.
# Поэтому этот скрипт не заменяет build-ext.sh, а стоит рядом: им собирается то, где выигрыш
# измерен (MIPS), а остальное по-прежнему zig. Решение о том, что выкладывать, остаётся за
# человеком — здесь только воспроизводимый рецепт.
#
# ЧИСЛА ВЫШЕ СНЯТЫ НА mbedtls 3.6.2, которую в выпуске 1.10 сменила wolfSSL (шаг 1;
# docs/architecture.md, «Криптография»). Рецепт переведён на неё — тот же список файлов и те же
# опции (build/wolfssl/build.sh и user_settings.h), что у zig, — но НА SDK ЕЩЁ НЕ ПРОГОНЯЛСЯ: на
# машине, где шёл переезд, SDK OpenWrt нет. Выигрыш gcc над LLVM на MIPS надо перемерить заново —
# он был свойством кода ChaCha20 в mbedtls, а у wolfSSL этот код другой.
#
#     sh build/build-ext-sdk.sh <каталог SDK> <исходники wolfSSL> <router|server> <выход> [версия] [ревизия]
#
# Исходники wolfSSL — той же версии, что в образе: sh build/wolfssl/fetch.sh <каталог> (сверит сумму).
set -eu

SDK="${1:?нужен каталог распакованного OpenWrt SDK}"
WSRC="${2:?нужен каталог исходников wolfSSL (sh build/wolfssl/fetch.sh <каталог>)}"
ROLE="${3:?нужна роль: router или server}"
OUT="${4:?нужен путь выходного файла}"
VERSION="${5:-0.0.0}"
REV="${6:-неизвестна}"

SRC=$(cd "$(dirname "$0")/.." && pwd)
TC=$(echo "$SDK"/staging_dir/toolchain-*)
[ -d "$TC/bin" ] || { echo "в $SDK нет staging_dir/toolchain-*/bin"; exit 2; }
# STAGING_DIR обязателен: без него gcc из SDK предупреждает на каждом файле и ищет заголовки не там.
export STAGING_DIR="$SDK/staging_dir"
export PATH="$TC/bin:$PATH"
CC=$(ls "$TC"/bin/*-openwrt-linux-gcc | head -1)
[ -x "$CC" ] || { echo "не нашёл gcc в $TC/bin"; exit 2; }

# -O2, а не -Os: см. таблицу в шапке. Флаги процессора берутся те же, что у OpenWrt для этой цели
# (include/target.mk: CPU_CFLAGS_24kc).
OPT="-O2 -mips32r2 -mtune=24kc -flto"

# wolfSSL — тем же рецептом, что у zig (build/wolfssl/build.sh: список файлов, опции, отказ
# компиляции файла называется словами «не удалась» — их читает барьер релиза), только компилятор
# SDK. Архив — в каталоге сборки дерева, с отпечатком: пересобирается, когда меняются опции.
WLIB="$SRC/build/wolfssl-obj/sdk-$(basename "$TC")/libwolfssl.a"
CC="$CC" AR="$(ls "$TC"/bin/*-openwrt-linux-gcc-ar | head -1)" \
    CFLAGS="$OPT -ffunction-sections -fdata-sections" \
    sh "$SRC/build/wolfssl/build.sh" "$WSRC" "$WLIB" asm
WCFLAGS=$(cat "$WLIB.cflags")

# Списки файлов — из build/sources.mk, одни на все сборки. До этого здесь жила своя копия,
# и она отстала от релизной на шесть файлов (hwid, ctl, awg, certverify, tgws, tlsprobe):
# рецепт не линковался вовсе, а заметить это было нечем.
export SOURCES_MK="$SRC/build/sources.mk"
. "$SRC/build/sources.sh"
case "$ROLE" in
  router) FILES="$(profile_src extended "$SRC/")" && ROLEDEF="$(profile_var PROFILE_DEFS_extended)" ;;
  server) FILES="$(profile_src server "$SRC/")" && ROLEDEF="$(profile_var PROFILE_DEFS_server)" ;;
  *) echo "неизвестная роль: $ROLE (router|server)" >&2; exit 2 ;;
esac
[ -n "${FILES:-}" ] || { echo "нет списка файлов для роли $ROLE" >&2; exit 2; }
STEER_INC="$(for d in $(profile_var INC_DIRS); do printf -- '-I%s/%s ' "$SRC" "$d"; done)"
# Определения стороннего кода в ядре (libyaml: -DHAVE_CONFIG_H) — см. THIRD_DEFS в sources.mk.
THIRD_DEFS="$(profile_var THIRD_DEFS)"

# -latomic ЗДЕСЬ НЕТ, и это следствие находки того же замера. Сначала gcc его потребовал: на
# 32-битной цели атомарная операция над 64-битным словом не выражается одной командой и уходит в
# libatomic — то есть в захват глобального замка, а для last_auth это замок на КАЖДЫЙ подтверждённый
# кадр. Метки, которые читает чужой поток, после этого стали тридцатидвухбитными (xsh_ms в xshub.c),
# и ключ перестал быть нужен: обе половины линкуются без него, размер тот же. zig подставлял такие
# вызовы сам, поэтому цена была и раньше — её просто никто не видел.
#
# СВЯЗЫВАНИЕ СТАТИЧЕСКОЕ, и это выбор, а не умолчание. Динамическое дало бы 392 612 байт вместо
# 574 552 (−31,7%) при +1,2% на пакете — но привязало бы бинарник к рантайму выпуска OpenWrt, а
# проект носит один файл на несколько выпусков. Числа и оговорки — в docs/xsteer.md.
# shellcheck disable=SC2086
"$CC" $OPT -w -static -s -Wl,--gc-sections \
    $STEER_INC $THIRD_DEFS $WCFLAGS $ROLEDEF \
    -DSTEER_VERSION="\"$VERSION\"" -DSTEER_REV="\"$REV\"" \
    -o "$OUT" \
    $FILES "$WLIB" -lpthread

printf '%s: %s байт\n' "$OUT" "$(stat -c %s "$OUT")"
